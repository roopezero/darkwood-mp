using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace DarkwoodMP.Codemod.Loading;

/// Builds the plugin's compilation without MSBuild: the same files, language
/// version, symbols and references as the real build, so every decision a
/// stage takes from the semantic model holds for the real DLL.
static class PluginLoader
{
    /// The real build's /define list.
    static readonly string[] Symbols =
    {
        "TRACE", "RELEASE", "NETFRAMEWORK", "NET472",
        "NET20_OR_GREATER", "NET30_OR_GREATER", "NET35_OR_GREATER",
        "NET40_OR_GREATER", "NET45_OR_GREATER", "NET451_OR_GREATER",
        "NET452_OR_GREATER", "NET46_OR_GREATER", "NET461_OR_GREATER",
        "NET462_OR_GREATER", "NET47_OR_GREATER", "NET471_OR_GREATER",
        "NET472_OR_GREATER",
    };

    /// Generated by the real build from the mod's version. It is in memory
    /// only, so no stage can rewrite it.
    const string ModVersion =
        "namespace DarkwoodMP { internal static class ModVersion "
        + "{ public const string Text = \"0.0.0\"; } }";

    /// Loads src/DarkwoodMP, or another copy of the same sources.
    public static PluginProject Load(RepoPaths paths, string sourceDir = null)
    {
        if (sourceDir == null)
        {
            sourceDir = paths.PluginSource;
        }
        sourceDir = Path.GetFullPath(sourceDir);
        var parse = ParseOptions(paths);
        var sources = ReadSources(sourceDir, parse);
        var trees = new List<SyntaxTree>(sources);
        trees.Add(CSharpSyntaxTree.ParseText(
            ModVersion, parse, "ModVersion.g.cs"));

        var compilation = CSharpCompilation.Create(
            "DarkwoodMP",
            trees,
            ReferenceList.Read(paths),
            CompileOptions());
        var diagnostics = compilation.GetDiagnostics();
        RequireClean(compilation, diagnostics, sourceDir);
        int warnings = diagnostics.Count(
            d => d.Severity == DiagnosticSeverity.Warning);
        return new PluginProject(sourceDir, compilation, sources, warnings);
    }

    /// The language version comes from the file the real build reads it from.
    public static CSharpParseOptions ParseOptions(RepoPaths paths)
    {
        var props = File.ReadAllText(paths.BuildProps);
        var match = Regex.Match(props, "<LangVersion>([^<]+)</LangVersion>");
        if (!match.Success)
        {
            throw new Stop("No <LangVersion> found in " + paths.BuildProps);
        }
        var text = match.Groups[1].Value;
        if (!LanguageVersionFacts.TryParse(text, out var version))
        {
            throw new Stop("Unknown language version: " + text);
        }
        return new CSharpParseOptions(
            version, DocumentationMode.Parse, SourceCodeKind.Regular, Symbols);
    }

    public static CSharpCompilationOptions CompileOptions()
    {
        return new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary)
            .WithOptimizationLevel(OptimizationLevel.Release)
            .WithAllowUnsafe(true)
            .WithDeterministic(true)
            .WithNullableContextOptions(NullableContextOptions.Disable)
            .WithConcurrentBuild(false)
            // Unity's DLLs reference mscorlib 2.0.0.0; this is the comparer
            // csc uses for .NET Framework, so there is no CS1701 noise.
            .WithAssemblyIdentityComparer(
                DesktopAssemblyIdentityComparer.Default);
    }

    /// Sorted, so the file order (and the metadata order) is stable.
    static List<SyntaxTree> ReadSources(string dir, CSharpParseOptions parse)
    {
        if (!Directory.Exists(dir))
        {
            throw new Stop("No such source folder: " + dir);
        }
        var files = Directory
            .GetFiles(dir, "*.cs", SearchOption.AllDirectories)
            .Where(f => !IsBuildOutput(dir, f))
            .OrderBy(f => f, StringComparer.Ordinal);
        var trees = new List<SyntaxTree>();
        foreach (var file in files)
        {
            var text = SourceText.From(
                File.ReadAllText(file),
                Encoding.UTF8,
                SourceHashAlgorithm.Sha256);
            trees.Add(CSharpSyntaxTree.ParseText(text, parse, file));
        }
        if (trees.Count == 0)
        {
            throw new Stop("No .cs files under " + dir);
        }
        return trees;
    }

    static bool IsBuildOutput(string dir, string file)
    {
        var relative = Path.GetRelativePath(dir, file).Replace('\\', '/');
        return relative.StartsWith("bin/", StringComparison.Ordinal)
            || relative.StartsWith("obj/", StringComparison.Ordinal);
    }

    static void RequireClean(
        CSharpCompilation compilation,
        IEnumerable<Diagnostic> diagnostics,
        string dir)
    {
        var errors = diagnostics
            .Where(d => d.Severity == DiagnosticSeverity.Error)
            .ToList();
        if (errors.Count > 0)
        {
            var shown = string.Join(
                "\n", errors.Take(20).Select(e => "  " + e));
            throw new Stop(
                "The sources in " + dir + " have " + errors.Count
                    + " compile errors. Nothing was changed. First errors:\n"
                    + shown);
        }
        if (compilation.GetTypeByMetadataName("UnityEngine.Object") == null)
        {
            throw new Stop(
                "UnityEngine.Object doesn't resolve, so a stage couldn't tell "
                    + "Unity objects from other types. Check that the game is "
                    + "installed (or set GameDir).");
        }
    }
}
